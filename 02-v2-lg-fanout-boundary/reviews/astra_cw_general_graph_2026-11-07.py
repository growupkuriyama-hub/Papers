ZERO=(0,0,0)
def plus(a,b): return tuple(x+y for x,y in zip(a,b))
def minus(a,b): return tuple(x-y for x,y in zip(a,b))
def mask(p): return sum(1<<i for i,x in enumerate(p) if x)
def graphs(prefix=(0,)):
    if len(prefix)==6:
        yield prefix; return
    for x in range(max(prefix)+2): yield from graphs(prefix+(x,))
def edges(g): return tuple(zip(g[::2],g[1::2]))
def walks(g,limit):
    """DP of (start,end,Parikh); preserves all Parikh vectors, not word multiplicity."""
    E=edges(g); allstates=set(); layer=set()
    for i,(s,t) in enumerate(E):
        p=tuple(int(j==i) for j in range(3)); layer.add((s,t,p))
    for _ in range(limit):
        allstates |= layer; nxt=set()
        for s,t,p in layer:
            for i,(u,v) in enumerate(E):
                if t==u:
                    q=list(p); q[i]+=1; nxt.add((s,v,tuple(q)))
        layer=nxt
    return allstates

def interior_c(g):
    # State remembers a noninitial c awaiting a following letter, or witnessed interior c.
    E=edges(g); seen={(t,1<<i,False,False) for i,(s,t) in enumerate(E)}; todo=list(seen)
    while todo:
        v,m,pending,done=todo.pop()
        if done and m&3==3: return True
        for i,(s,t) in enumerate(E):
            if s!=v: continue
            z=(t,m|1<<i,i==2,done or pending)
            if z not in seen: seen.add(z); todo.append(z)
    return False

def strong(g,letters):
    E=[edges(g)[i] for i in letters]; V=set(sum(([s,t] for s,t in E),[]))
    for start in V:
        reach={start}
        while True:
            nxt=reach|{t for s,t in E if s in reach}
            if nxt==reach: break
            reach=nxt
        if reach!=V: return False
    return True

def classification(g):
    long=any(mask(p)==3 and sum(p)>=3 for s,t,p in walks(g,4))
    return long,interior_c(g),strong(g,[0,1]) and strong(g,[0,1,2])

def hnf(vectors):
    """Canonical row Hermite normal form: positive pivots; entries above reduced."""
    a=[list(v) for v in set(vectors) if any(v)]; k=0
    for j in range(3):
        cand=[i for i in range(k,len(a)) if a[i][j]]
        if not cand: continue
        a[k],a[cand[0]]=a[cand[0]],a[k]
        for i in range(k+1,len(a)):
            while a[i][j]:
                q=a[k][j]//a[i][j]
                a[k]=[x-q*y for x,y in zip(a[k],a[i])]
                a[k],a[i]=a[i],a[k]
        if a[k][j]<0: a[k]=[-x for x in a[k]]
        for i in range(k):
            q=a[i][j]//a[k][j]; a[i]=[x-q*y for x,y in zip(a[i],a[k])]
        k+=1
    return tuple(tuple(r) for r in a[:k])
def subset(A,B): return hnf(list(A)+list(B))==hnf(B)

def lattice_data(g,L):
    W=walks(g,L); V=range(max(g)+1); C={}; D={}; bases={}
    for x in V:
        for m in (3,7): C[x,m]=hnf(p for s,t,p in W if s==t==x and mask(p)&~m==0)
    for s,t in it.product(V,repeat=2):
        for m in (3,7):
            ps=sorted(p for a,b,p in W if (a,b)==(s,t) and mask(p)==m)
            if ps:
                bases[s,t,m]=ps[0]; D[s,t,m]=hnf(minus(p,ps[0]) for p in ps)
    pairs=sorted({(s,t) for s,t,m in D})
    for s,t in pairs:
        for m in (3,7):
            if (s,t,m) in D: assert subset(D[s,t,m], C[s,m]+C[t,m]),(g,s,t,m,'CW1')
        if (s,t,3) in D and (s,t,7) in D:
            assert any(x[2] for x in C[s,7]+C[t,7]),(g,s,t,'CW2c')
            assert subset([minus(bases[s,t,7],bases[s,t,3])],C[s,7]+C[t,7])
            assert any(subset(D[s,t,3],C[r,3]) for r in set(g[:4]))
    return C,D,pairs

def predicted_lattices(g, C, D):
    E=edges(g); unit=[tuple(int(i==j) for i in range(3)) for j in range(3)]
    # For a two-vertex support, integer circulations are generated by loops
    # and pairs consisting of one edge in each direction.
    def cycles(m):
        gens=[]
        for i,(s,t) in enumerate(E):
            if m>>i&1 and s==t: gens.append(unit[i])
        for i in range(3):
            for j in range(i):
                if m>>i&1 and m>>j&1 and E[i][0]!=E[i][1] and E[i]==E[j][::-1]:
                    gens.append(plus(unit[i],unit[j]))
        return hnf(gens)
    for (x,m),actual in C.items():
        letters=[i for i in range(3) if m>>i&1]
        if strong(g,letters): expected=cycles(m)
        else: expected=hnf(unit[i] for i in letters if E[i]==(x,x))
        assert actual==expected,('C formula',g,x,m,actual,expected)
    for (s,t,m),actual in D.items():
        # Every allowed support here is either strongly connected or one bridge plus loops.
        assert actual==cycles(m),('D formula',g,s,t,m,actual,cycles(m))

def classify_run():
    G=list(graphs()); assert len(G)==203
    counts=Counter(classification(g) for g in G)
    selected=[g for g in G if classification(g)[:2]==(True,True)]
    assert len(selected)==17
    rows=[]; total=0
    for idx,g in enumerate(selected,1):
        data=[lattice_data(g,L) for L in (7,10,14)]
        assert data[0]==data[1]==data[2]
        C,D,pairs=data[-1]; predicted_lattices(g,C,D); total+=len(pairs)
        row={'id':idx,'g':g,'pairs':pairs,'C':{str(k):v for k,v in C.items()},'D':{str(k):v for k,v in D.items()}}
        rows.append(row)
        print(idx,g,pairs,flush=True)
    assert total==41
    remaining=[{'g':g,'class':classification(g)} for g in G if g not in selected]
    result={'counts':{str(k):v for k,v in counts.items()},'rows':rows,'remaining':remaining}
    Path('cw_lattices.json').write_text(json.dumps(result,indent=2))
    print('CLASSIFICATION',result['counts'],'pairs',total,flush=True)
    return selected



class FiniteTypes:
    def __init__(self,g,moduli,phi):
        self.moduli=moduli; self.zero=(0,)*len(moduli)
        self.add=lambda a,b:tuple((x+y)%n for x,y,n in zip(a,b,moduli))
        self.sub=lambda a,b:tuple((x-y)%n for x,y,n in zip(a,b,moduli))
        E=edges(g)
        seen={(s,t,phi[i],1<<i) for i,(s,t) in enumerate(E)}; todo=list(seen)
        while todo:
            s,t,v,m=todo.pop()
            for i,(u,w) in enumerate(E):
                if t==u:
                    z=(s,w,self.add(v,phi[i]),m|1<<i)
                    if z not in seen: seen.add(z); todo.append(z)
        self.R=sorted(seen); self.index={z:i for i,z in enumerate(self.R)}; self.n=len(seen)
        # Context words are either empty or a realizable nonempty path type.
        context=[None]+self.R; rows=[]
        for x in self.R:
            row={}
            for li,l in enumerate(context):
                if l is not None and l[1]!=x[0]: continue
                for ri,r in enumerate(context):
                    if r is not None and r[0]!=x[1]: continue
                    z=(l[0] if l else x[0],r[1] if r else x[1],
                       self.add(self.add(l[2] if l else self.zero,x[2]),r[2] if r else self.zero),
                       (l[3] if l else 0)|x[3]|(r[3] if r else 0))
                    row[li,ri]=self.index[z]
            rows.append(row)
        self.rows=rows
        # Each comparison stores distinct pairs of context outcomes. -1 means non-path.
        comparisons=set()
        for i,x in enumerate(self.R):
            for j in range(i):
                if self.R[j][3]!=x[3]: continue
                pairs={(rows[i].get(c,-1),rows[j].get(c,-1)) for c in rows[i].keys()|rows[j].keys()}
                if all(a==b for a,b in pairs): continue
                positive=tuple(sorted({(1<<a)|(1<<b) for a,b in pairs if a>=0 and b>=0}))
                if not positive: continue
                moves=tuple(sorted({(1<<a if a>=0 else 0,1<<b if b>=0 else 0) for a,b in pairs if a!=b}))
                comparisons.add((positive,moves))
        self.comparisons=list(comparisons)
        self.k_cache={}
        self.blocks=defaultdict(list)
        for i,(s,t,v,m) in enumerate(self.R):
            if m in (3,7): self.blocks[s,t,m].append((i,v))

    def close(self,p,negative):
        # Propagate positive and negative literals of the exact SUB1 implications.
        while True:
            old=(p,negative)
            for triggers,moves in self.comparisons:
                active=any(p&t==t for t in triggers)
                if active:
                    for a,b in moves:
                        if p&a or p&b:
                            if not a or not b: return None
                            p |= a|b
                        if not a or not b or negative&a or negative&b:
                            negative |= a|b
                else:
                    mismatch=any((p&a and (not b or negative&b)) or
                                 (p&b and (not a or negative&a)) for a,b in moves)
                    if mismatch:
                        for t in triggers:
                            missing=t&~p
                            if missing and missing&(missing-1)==0:
                                negative |= missing
                if p&negative: return None
            if (p,negative)==old: return p,negative

    def exact_sub1(self,p):
        # Independent final criterion: distributions disjoint or equal.
        seen=defaultdict(dict)
        for x,row in zip(self.R,self.rows):
            dist=frozenset(c for c,i in row.items() if p>>i&1)
            inv=seen[x[3]]
            for c in dist:
                if c in inv and inv[c]!=dist: return False
                inv[c]=dist
        return True

    def subgroup(self,gens):
        h={self.zero}; todo=[self.zero]
        while todo:
            x=todo.pop()
            for g in gens:
                y=self.add(x,g)
                if y not in h: h.add(y); todo.append(y)
        return h

    def check_K(self,p):
        sets={}; groups={}
        for key,block in self.blocks.items():
            local=p&sum(1<<i for i,v in block)
            cachekey=(key,local)
            if cachekey not in self.k_cache:
                vals={v for i,v in block if local>>i&1}
                H=set()
                if vals:
                    base=min(vals); H=self.subgroup([self.sub(v,base) for v in vals])
                    assert vals=={self.add(base,h) for h in H},('K1',key,vals)
                self.k_cache[cachekey]=(vals,H)
            vals,H=self.k_cache[cachekey]; sets[key]=vals; groups[key]=H
        for s,t in {(s,t) for s,t,m in sets}:
            a=sets.get((s,t,3),set()); b=sets.get((s,t,7),set())
            if not a or not b: continue  # inactive contents excluded from (16)
            H=groups[s,t,7]; base=min(a)
            realized={v for i,v in self.blocks[s,t,3]}
            assert a==realized&{self.add(base,h) for h in H},('K2',s,t,a,b)

    def universal_K(self):
        """Exhaustive universal Horn entailment, quantifying over ALL P.

        Finite nonempty sets are cosets iff closed under x+y-z.
        After K1, common-H K2 is equivalent to the two cross-content shifts.
        Each query is decided by the least SUB1 model containing its premises.
        """
        queries={}
        def require(premises,key,value):
            seed=sum(1<<i for i in set(premises))
            target=self.index.get((key[0],key[1],value,key[2]))
            queries.setdefault(seed,set()).add(target)
        for key,block in self.blocks.items():
            for (i,x),(j,y),(k,z) in it.product(block,repeat=3):
                require([i,j,k],key,self.sub(self.add(x,y),z))
        for s,t in {(s,t) for s,t,m in self.blocks}:
            two=self.blocks.get((s,t,3),[]); three=self.blocks.get((s,t,7),[])
            realized={v for i,v in two}
            for (i,x),(j,y),(k,z) in it.product(three,two,two):
                require([i,j,k],(s,t,7),self.sub(self.add(x,y),z))
            for (i,x),(j,y),(k,z) in it.product(two,three,three):
                value=self.sub(self.add(x,y),z)
                if value in realized: require([i,j,k],(s,t,3),value)
        impossible=0
        for seed,targets in queries.items():
            closed=self.close(seed,0)
            if closed is None:
                impossible+=1; continue
            p,negative=closed
            assert self.exact_sub1(p)
            for target in targets:
                assert target is not None and p>>target&1,('universal K counterexample',seed,p,target)
        return len(queries),impossible,sum(map(len,queries.values()))

    def all_models(self):
        full=(1<<self.n)-1
        def visit(p,negative):
            closed=self.close(p,negative)
            if closed is None: return
            p,negative=closed
            remaining=full&~(p|negative)
            if not remaining:
                yield p; return
            bit=remaining&-remaining
            yield from visit(p,negative|bit)
            yield from visit(p|bit,negative)
        yield from visit(0,0)

def finite_run(selected,mode='z2',resume=False):
    families=[((2,),list(it.product(list(it.product(range(2))),repeat=3)))]
    if mode in ('suite','enum3'):
        families += [((3,),[((1,),(0,),(0,))]),
                     ((2,2),[((1,0),(0,1),(0,0))])]
    if mode=='suite':
        families += [((6,),[((1,),(0,),(0,))])]
    if mode=='all':
        families += [((3,),list(it.product(list(it.product(range(3))),repeat=3))),
                     ((2,2),list(it.product(list(it.product(range(2),repeat=2)),repeat=3))),
                     ((6,),list(it.product(list(it.product(range(6))),repeat=3)))]
    output=Path('cw_finite_'+mode+'.json')
    results=json.loads(output.read_text()) if resume and output.exists() else []
    done={(tuple(row['group']),row['graph']) for row in results}
    for mods,phis in families:
        for idx,g in enumerate(selected,1):
            if (mods,idx) in done: continue
            total=0; systems=0; start=time.time()
            for phi in phis:
                system=FiniteTypes(g,mods,phi); count=0
                for p in system.all_models():
                    # Closure constraints are exactly SUB1; direct distributions cross-check samples.
                    if count<10 or count%1000==0: assert system.exact_sub1(p)
                    system.check_K(p); count+=1
                total+=count; systems+=1
            row={'group':mods,'graph':idx,'phi_count':systems,'SUB1_count':total,'seconds':round(time.time()-start,3)}
            results.append(row); print('FINITE',row,flush=True)
            Path('cw_finite_'+mode+'.json').write_text(json.dumps(results,indent=2))
    return results

def universal_run(selected):
    results=[]
    for mods,phi in [((2,),((1,),(0,),(0,))),
                     ((3,),((1,),(0,),(0,))),
                     ((2,2),((1,0),(0,1),(0,0))),
                     ((6,),((1,),(0,),(0,)))]:
        for idx,g in enumerate(selected,1):
            start=time.time(); system=FiniteTypes(g,mods,phi)
            count,impossible,implications=system.universal_K()
            row={'group':mods,'graph':idx,'types':system.n,'seeds':count,
                 'inconsistent_seeds':impossible,'implications':implications,
                 'seconds':round(time.time()-start,3)}
            results.append(row); print('UNIVERSAL',row,flush=True)
            Path('cw_universal.json').write_text(json.dumps(results,indent=2))
    return results

def audit_primitives():
    # HNF invariance under unimodular row moves, including nonsaturated lattices.
    rng=random.Random(195)
    for _ in range(500):
        B=[tuple(rng.randint(-12,12) for _ in range(3)) for j in range(5)]
        canonical=hnf(B)
        for j in range(12):
            a,b=rng.sample(range(len(B)),2); k=rng.randint(-3,3)
            B[a]=tuple(x+k*y for x,y in zip(B[a],B[b]))
        assert hnf(B)==canonical
        assert hnf(canonical)==canonical
    # Exhaustive raw-subset check of the SUB1 model enumerator.
    selected=[g for g in graphs() if classification(g)[:2]==(True,True)]
    systems=[FiniteTypes(g,(1,),((0,),(0,),(0,))) for g in selected]
    systems.append(FiniteTypes((0,)*6,(2,),((1,),(0,),(0,))))
    tested=0
    for system in systems:
        direct={p for p in range(1<<system.n) if system.exact_sub1(p)}
        enumerated=set(system.all_models())
        assert direct==enumerated
        tested+=1<<system.n
    print('AUDIT',{'HNF':500,'raw_subset_systems':len(systems),'raw_subsets':tested},flush=True)

