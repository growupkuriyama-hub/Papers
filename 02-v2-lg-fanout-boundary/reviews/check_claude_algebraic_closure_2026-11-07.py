def classify(cfg):
    tail = [cfg[0], cfg[2], cfg[4]]; head = [cfg[1], cfg[3], cfg[5]]
    # states: (vertex, content frozenset, phase); phase 0 start,1 >=1 letter,2 pending c,3 interior c seen
    start = []
    for s in range(3):
        ph = 1
        start.append((head[s], frozenset({s}), 1))
    seen = set(start); dq = deque(start)
    interior = False
    while dq:
        v, M, ph = dq.popleft()
        if ph == 3 and {0, 1} <= M:
            interior = True
        for s in range(3):
            if tail[s] == v:
                nph = ph
                if ph == 2:
                    nph = 3
                if s == 2 and nph == 1:
                    nph = 2
                st = (head[s], M | {s}, nph)
                if st not in seen:
                    seen.add(st); dq.append(st)
    # long ab-paths
    def walks(maxlen, letters):
        res = []
        for L in range(1, maxlen + 1):
            for w in itertools.product(letters, repeat=L):
                if all(head[w[i]] == tail[w[i + 1]] for i in range(L - 1)):
                    res.append(w)
        return res
    abw = [w for w in walks(4, [0, 1]) if set(w) == {0, 1}]
    unbounded_ab = any(len(w) >= 3 for w in abw)
    def strongly_connected(M):
        V = set([tail[s] for s in M] + [head[s] for s in M])
        adj = defaultdict(set); radj = defaultdict(set)
        for s in M:
            adj[tail[s]].add(head[s]); radj[head[s]].add(tail[s])
        v0 = next(iter(V))
        def reach(a):
            S = {v0}; st = [v0]
            while st:
                x = st.pop()
                for y in a[x]:
                    if y not in S:
                        S.add(y); st.append(y)
            return S
        return reach(adj) == V and reach(radj) == V
    sc = strongly_connected([0, 1]) and strongly_connected([0, 1, 2])
    return unbounded_ab, interior, sc


