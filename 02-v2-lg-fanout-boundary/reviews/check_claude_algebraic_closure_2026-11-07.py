def lat2_member(gens, v):
    """membership of v in the Z-span of 2D integer vectors gens (exact, via HNF)."""
    rows = [list(g) for g in gens if g != (0, 0)]
    # HNF over Z for 2 columns
    basis = []
    # column 0
    def reduce(rows):
        rows = [r[:] for r in rows if r != [0, 0]]
        piv = []
        for col in range(2):
            rows_c = [r for r in rows if r[col] != 0 and all(r[k] == 0 for k in range(col))]
            others = [r for r in rows if not (r[col] != 0 and all(r[k] == 0 for k in range(col)))]
            while len(rows_c) > 1:
                rows_c.sort(key=lambda r: abs(r[col]))
                a = rows_c[0]
                new = [a]
                for r in rows_c[1:]:
                    q = r[col] // a[col]
                    rr = [r[k] - q * a[k] for k in range(2)]
                    if rr[col] != 0:
                        new.append(rr)
                    elif any(rr):
                        others.append(rr)
                rows_c = new
            if rows_c:
                piv.append(rows_c[0])
            rows = others
        return piv, rows
    piv, rest = reduce(rows)
    # rest are rows with zeros in pivots; loop until stable
    while rest and any(any(r) for r in rest):
        piv, rest = reduce(piv + rest)
    x = list(v)
    for p in piv:
        col = 0 if p[0] != 0 else 1
        if x[col] % p[col] != 0:
            return False
        q = x[col] // p[col]
        x = [x[k] - q * p[k] for k in range(2)]
    return x == [0, 0]

def closure2(seed, box):
    """closure of seed in the quadrant [1,box]^2 under moves by own differences (both points in quadrant)"""
    S = set(seed)
    changed = True
    while changed:
        changed = False
        D = set((q2[0] - q[0], q2[1] - q[1]) for q in S for q2 in S if q != q2)
        new = set()
        for d in D:
            for x in range(1, box + 1):
                for y in range(1, box + 1):
                    a = (x, y); b = (x + d[0], y + d[1])
                    if 1 <= b[0] <= box and 1 <= b[1] <= box:
                        if (a in S) != (b in S):
                            new.add(a); new.add(b)
        if not new <= S:
            S |= new; changed = True
    return S

