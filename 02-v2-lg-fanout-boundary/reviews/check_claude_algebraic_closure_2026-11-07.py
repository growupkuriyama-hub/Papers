def in_lattice3(gens, v):
    B = hnf3(gens)
    x = list(v)
    for row in B:
        col = next(k for k in range(3) if row[k] != 0)
        if x[col] % row[col]:
            return False
        q = x[col] // row[col]
        x = [x[k] - q * row[k] for k in range(3)]
    return x == [0, 0, 0]

def hnf3(gens):
    rows = [list(g) for g in gens if any(g)]
    out = []
    for col in range(3):
        cand = [r for r in rows if r[col] != 0]
        rest = [r for r in rows if r[col] == 0]
        while len(cand) > 1:
            cand.sort(key=lambda r: abs(r[col]))
            a = cand[0]; nc = [a]
            for r in cand[1:]:
                q = r[col] // a[col]
                rr = [r[k] - q * a[k] for k in range(3)]
                (nc if rr[col] != 0 else rest).append(rr)
            cand = nc
        if cand:
            a = cand[0]
            if a[col] < 0:
                a = [-t for t in a]
            out.append(a)
        rows = [r for r in rest if any(r)]
    return out

