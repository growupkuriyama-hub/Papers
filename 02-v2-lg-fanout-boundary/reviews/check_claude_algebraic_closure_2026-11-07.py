def is_single_coset(vals, Lam, n):
    if not vals:
        return True
    p0 = next(iter(vals))
    H = subgroup_gen(n, [p - p0 for p in vals])
    full = frozenset((p0 + h) % n for h in H) & Lam
    return full == vals

