def closed_check(S):
    D = set((b[0] - a[0], b[1] - a[1]) for a in S for b in S if a != b)
    for d in D:
        for a in S:
            for sgn in (1, -1):
                b = (a[0] + sgn * d[0], a[1] + sgn * d[1])
                if b[0] >= 1 and b[1] >= 1 and b not in S:
                    return False
    return True

def finite_closed_sets(box=5, maxk=5):
    pts = [(x, y) for x in range(1, box + 1) for y in range(1, box + 1)]
    found = 0; noncollinear = 0
    for k in range(2, maxk + 1):
        for S in itertools.combinations(pts, k):
            if closed_check(S):
                found += 1
                p0 = S[0]
                vs = [(p[0] - p0[0], p[1] - p0[1]) for p in S[1:]]
                col = all(vs[0][0] * v[1] - vs[0][1] * v[0] == 0 for v in vs)
                if not col:
                    noncollinear += 1
    return found, noncollinear


