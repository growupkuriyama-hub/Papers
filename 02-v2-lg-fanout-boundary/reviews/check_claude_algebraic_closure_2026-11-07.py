# ---------- F: lifting blows up thickness ----------
def lifting_example(nmax=12):
    out = []
    for n in range(1, nmax + 1):
        # G_n: A_i -> A_{i-1} A_{i-1} | c (i>=1); A_0 -> a | c ; S -> A_n
        tau = {0: 1}
        for i in range(1, n + 1):
            tau[i] = min(2 * tau[i - 1], 1)
        rho = max([1] + [2 * tau[i - 1] for i in range(1, n + 1)] + [tau[n]])
        # lifted along the 2-state DFA 'has c' : A_i^{(0,0)} has only c-free yields = a^(2^i)
        tau00 = {0: 1}
        for i in range(1, n + 1):
            tau00[i] = 2 * tau00[i - 1]
        rho_lift = max(2 * tau00[i - 1] for i in range(1, n + 1))
        out.append((n, rho, rho_lift))
    return out

