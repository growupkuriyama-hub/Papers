def lemmaV(st):
    """Lemma V: comp with nu_l = 0 => every phi containing l is c-free."""
    for (i, s, e) in st.layout:
        ph = st.xs[i][s:e]
        for L in 'ab':
            if nu(st.xs[i], L) == 0 and st.xs[i].count('c') >= 1 and L in ph and 'c' in ph: return False
    return True

